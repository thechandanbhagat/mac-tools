import AppKit
import ImageIO
import XCTest
@testable import MacTools

@MainActor
final class ClipboardHistoryTests: XCTestCase {
    func testCountAndByteBudgetsEvictOldestItems() {
        var history = ClipboardHistory(maximumCount: 2, maximumBytes: 9)
        history.insert(.text("first")); history.insert(.text("two")); history.insert(.text("third"))
        XCTAssertEqual(history.entries.map(\.content), [.text("third"), .text("two")])
        XCTAssertEqual(history.byteCount, 8)
        history.insert(.text("oversized item"))
        XCTAssertEqual(history.entries.count, 2)
    }
    func testDuplicateMovesToFrontAndClearReleasesItems() {
        var history = ClipboardHistory()
        history.insert(.text("one")); history.insert(.text("two")); history.insert(.text("one"))
        XCTAssertEqual(history.entries.map(\.content), [.text("one"), .text("two")])
        history.remove(id: history.entries[0].id)
        XCTAssertEqual(history.entries.map(\.content), [.text("two")])
        history.clear(); XCTAssertTrue(history.entries.isEmpty); XCTAssertEqual(history.byteCount, 0)
    }
    func testProtectedPasteboardTypesAreExcludedBeforeDecoding() {
        for type in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword", "com.vendor.Password", "com.keepass.secret"] {
            XCTAssertNil(ClipboardCandidate(types: [type, "public.utf8-plain-text"], text: "secret", imageData: nil).sanitized(), type)
        }
        XCTAssertEqual(ClipboardCandidate(types: ["public.utf8-plain-text"], text: "notes", imageData: nil).sanitized(), .text("notes"))
    }
    func testTextBoundsCountUTF8BytesAndRejectEmptyContent() {
        XCTAssertNil(ClipboardCandidate(types: [], text: "", imageData: nil).sanitized())
        XCTAssertNil(ClipboardCandidate(types: [], text: String(repeating: "é", count: 140_000), imageData: nil).sanitized())
        var history = ClipboardHistory()
        history.insert(.text(String(repeating: "a", count: ClipboardHistory.maximumTextBytes + 1)))
        XCTAssertTrue(history.entries.isEmpty)
    }
    func testImageNormalizationPreservesDimensionsBeyondPreviewSize() throws {
        let image = try makeImage(width: 2400, height: 10)
        let data = try XCTUnwrap(NSBitmapImageRep(cgImage: image).representation(using: .tiff, properties: [:]))
        guard case .image(let png, let width, let height) = ClipboardCandidate(types: ["public.tiff"], text: nil, imageData: data).sanitized() else {
            return XCTFail("Expected PNG image content")
        }
        XCTAssertEqual(width, 2400); XCTAssertEqual(height, 10)
        XCTAssertEqual(Array(png.prefix(8)), [137, 80, 78, 71, 13, 10, 26, 10])
        let source = try XCTUnwrap(CGImageSourceCreateWithData(png as CFData, nil))
        let decoded = try XCTUnwrap(CGImageSourceCreateImageAtIndex(source, 0, nil))
        XCTAssertEqual(decoded.width, 2400); XCTAssertEqual(decoded.height, 10)
    }
    func testInvalidOrOversizedImageDoesNotEnterHistory() {
        XCTAssertNil(ClipboardCandidate(types: [], text: nil, imageData: Data([1, 2, 3])).sanitized())
        XCTAssertNil(ClipboardCandidate(types: [], text: nil, imageData: Data(repeating: 0, count: ClipboardHistory.maximumItemBytes + 1)).sanitized())
    }
    func testStartsPausedWithoutReadingExistingClipboard() async {
        let access = FakeClipboardAccess()
        access.next = .init(types: [], text: "existing", imageData: nil)
        let model = ClipboardHistoryModel(isDemo: false, access: access)
        defer { model.shutdown() }
        XCTAssertEqual(access.readCount, 0); XCTAssertEqual(access.countReads, 0)
        XCTAssertFalse(model.isMonitoring)
        await model.captureChange()
        XCTAssertEqual(access.readCount, 0)
        model.start()
        await model.captureChange()
        XCTAssertTrue(model.history.entries.isEmpty)
        XCTAssertEqual(access.readCount, 0)
        access.count += 1; access.next = .init(types: [], text: "new copy", imageData: nil)
        await model.captureChange()
        XCTAssertEqual(model.history.entries.first?.content, .text("new copy"))
    }
    func testClipboardReplacementDuringReadCannotBypassConcealedTypes() async {
        let access = FakeClipboardAccess()
        let model = ClipboardHistoryModel(isDemo: false, access: access)
        defer { model.shutdown() }
        model.start()
        access.count += 1
        // Simulate old public types paired with the replacement item's protected payload.
        access.next = .init(types: ["public.utf8-plain-text"], text: "private replacement", imageData: nil)
        access.onRead = {
            access.count += 1
            access.next = .init(types: ["org.nspasteboard.ConcealedType"], text: "private replacement", imageData: nil)
            access.onRead = nil
        }
        await model.captureChange()
        XCTAssertTrue(model.history.entries.isEmpty)
        // The newer generation is retried and its actual privacy marker is respected.
        await model.captureChange()
        XCTAssertTrue(model.history.entries.isEmpty)
        access.count += 1
        access.next = .init(types: ["public.utf8-plain-text"], text: "ordinary copy", imageData: nil)
        await model.captureChange()
        XCTAssertEqual(model.history.entries.map(\.content), [.text("ordinary copy")])
        XCTAssertTrue(access.writes.isEmpty)
    }
    func testPauseClearAndShutdownDoNotWriteClipboard() async {
        let access = FakeClipboardAccess()
        let model = ClipboardHistoryModel(isDemo: false, access: access)
        model.start(); access.count += 1; access.next = .init(types: [], text: "sample", imageData: nil)
        await model.captureChange()
        model.pause(); access.count += 1
        let reads = access.readCount
        await model.captureChange()
        XCTAssertEqual(access.readCount, reads)
        model.clear(); XCTAssertTrue(model.history.entries.isEmpty)
        model.shutdown(); XCTAssertEqual(access.writes, [])
    }
    func testCopyRequiresExplicitActionAndDoesNotRecaptureOwnWrite() async {
        let access = FakeClipboardAccess()
        let model = ClipboardHistoryModel(isDemo: false, access: access)
        defer { model.shutdown() }
        model.start(); access.count += 1; access.next = .init(types: [], text: "sample", imageData: nil)
        await model.captureChange()
        XCTAssertTrue(access.writes.isEmpty)
        model.copySelected()
        XCTAssertEqual(access.writes, [.text("sample")])
        await model.captureChange()
        XCTAssertEqual(model.history.entries.count, 1)
        XCTAssertEqual(access.readCount, 1)
    }
    func testDemoCannotReadOrWriteHostClipboard() async {
        let access = FakeClipboardAccess()
        let model = ClipboardHistoryModel(isDemo: true, access: access)
        XCTAssertFalse(model.history.entries.isEmpty)
        model.start(); await model.captureChange(); model.copySelected(); model.clear(); model.shutdown()
        XCTAssertEqual(access.readCount, 0); XCTAssertEqual(access.countReads, 0); XCTAssertEqual(access.writes.count, 0)
    }
    func testSearchFiltersTextAndClearPreservesMonitoringChoice() async {
        let access = FakeClipboardAccess()
        let model = ClipboardHistoryModel(isDemo: false, access: access)
        defer { model.shutdown() }
        model.start(); access.count += 1; access.next = .init(types: [], text: "Project Notes", imageData: nil)
        await model.captureChange()
        model.query = "notes"; XCTAssertEqual(model.entries.count, 1)
        model.query = "other"; XCTAssertTrue(model.entries.isEmpty)
        model.clear(); XCTAssertTrue(model.isMonitoring); XCTAssertTrue(model.history.entries.isEmpty)
    }

    private func makeImage(width: Int, height: Int) throws -> CGImage {
        let context = try XCTUnwrap(CGContext(data: nil, width: width, height: height, bitsPerComponent: 8, bytesPerRow: 0,
                                             space: CGColorSpaceCreateDeviceRGB(), bitmapInfo: CGImageAlphaInfo.noneSkipLast.rawValue))
        context.setFillColor(CGColor(gray: 0.6, alpha: 1)); context.fill(CGRect(x: 0, y: 0, width: width, height: height))
        return try XCTUnwrap(context.makeImage())
    }
}

@MainActor
private final class FakeClipboardAccess: ClipboardAccess {
    var count = 1
    var countReads = 0
    var readCount = 0
    var writes: [ClipboardContent] = []
    var next: ClipboardCandidate?
    var onRead: (() -> Void)?
    var changeCount: Int { countReads += 1; return count }
    func candidate() -> ClipboardCandidate? {
        readCount += 1
        let value = next
        onRead?()
        return value
    }
    func write(_ content: ClipboardContent) -> Bool { writes.append(content); count += 1; return true }
}
