import CryptoKit
import Foundation
import ImageIO
import UniformTypeIdentifiers

enum ClipboardContent: Equatable, Sendable {
    case text(String)
    case image(Data, width: Int, height: Int)

    var byteCount: Int {
        switch self { case .text(let text): text.utf8.count; case .image(let data, _, _): data.count }
    }
    var searchableText: String {
        switch self { case .text(let text): text; case .image(_, let width, let height): "Image \(width) × \(height)" }
    }
    var menuTitle: String {
        let singleLine = searchableText
            .replacingOccurrences(of: "\n", with: " ")
            .trimmingCharacters(in: .whitespacesAndNewlines)
        if singleLine.count <= 40 { return singleLine }
        return String(singleLine.prefix(40)) + "…"
    }
    fileprivate var digest: String {
        let data: Data
        switch self { case .text(let text): data = Data(text.utf8); case .image(let image, _, _): data = image }
        return String(describing: SHA256.hash(data: data))
    }
}

struct ClipboardEntry: Identifiable, Equatable, Sendable {
    let id: UUID
    let content: ClipboardContent
    let capturedAt: Date
}

struct ClipboardCandidate: Sendable {
    let types: [String]
    let text: String?
    let imageData: Data?

    static func excludes(types: [String]) -> Bool {
        types.contains { type in
            let value = type.lowercased()
            return value.contains("concealed") || value.contains("transient")
                || value.contains("autogenerated") || value.contains("password")
                || value.contains("1password") || value.contains("keepass")
                || value == "com.agilebits.onepassword"
        }
    }

    func sanitized() -> ClipboardContent? {
        guard !Self.excludes(types: types) else { return nil }
        if let data = imageData, data.count <= ClipboardHistory.maximumItemBytes,
           let source = CGImageSourceCreateWithData(data as CFData, nil),
           let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
           let width = properties[kCGImagePropertyPixelWidth] as? Int,
           let height = properties[kCGImagePropertyPixelHeight] as? Int,
           width > 0, height > 0, width <= 16_000_000 / height,
           let image = CGImageSourceCreateThumbnailAtIndex(source, 0, [
               kCGImageSourceCreateThumbnailFromImageAlways: true,
               kCGImageSourceCreateThumbnailWithTransform: true,
               kCGImageSourceThumbnailMaxPixelSize: max(width, height)
           ] as CFDictionary) {
            let output = NSMutableData()
            guard let destination = CGImageDestinationCreateWithData(output, UTType.png.identifier as CFString, 1, nil) else { return nil }
            CGImageDestinationAddImage(destination, image, nil)
            guard CGImageDestinationFinalize(destination), output.length <= ClipboardHistory.maximumItemBytes else { return nil }
            return .image(output as Data, width: image.width, height: image.height)
        }
        guard let text, !text.isEmpty, text.utf8.count <= ClipboardHistory.maximumTextBytes else { return nil }
        return .text(text)
    }
}

/// Session-only storage. No pasteboard access or persistence occurs in this type.
struct ClipboardHistory: Sendable {
    static let maximumItemBytes = 8 * 1024 * 1024
    static let maximumTextBytes = 256 * 1024
    private(set) var entries: [ClipboardEntry] = []
    let maximumCount: Int
    let maximumBytes: Int

    init(maximumCount: Int = 100, maximumBytes: Int = 20 * 1024 * 1024) {
        self.maximumCount = max(0, maximumCount)
        self.maximumBytes = max(0, maximumBytes)
    }
    var byteCount: Int { entries.reduce(0) { $0 + $1.content.byteCount } }

    mutating func insert(_ content: ClipboardContent, at date: Date = .now) {
        guard maximumCount > 0, content.byteCount > 0,
              content.byteCount <= min(maximumBytes, Self.maximumItemBytes) else { return }
        if case .text(let text) = content, text.utf8.count > Self.maximumTextBytes { return }
        let digest = content.digest
        entries.removeAll { $0.content.digest == digest && $0.content == content }
        entries.insert(ClipboardEntry(id: UUID(), content: content, capturedAt: date), at: 0)
        while entries.count > maximumCount || byteCount > maximumBytes { entries.removeLast() }
    }
    mutating func remove(id: UUID) { entries.removeAll { $0.id == id } }
    mutating func clear() { entries.removeAll(keepingCapacity: false) }
}
